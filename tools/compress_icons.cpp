// compress_icons: turns the 4-bit icons of tools/icons_raw.h into the compressed data of src/display/IconsData.h.
// It decodes what it wrote and compares it with the source: a difference stops it (nothing is written).
//
//   usage: compress_icons > src/display/IconsData.h      (or ./tools/compress_icons.sh)
//
// Format (lossless): the pixels, row by row, as a stream of bits, the first bit being the most significant
// bit of the first byte. Each token starts with two bits:
//     00 nnnnn           a run of nnnnn + 1 pixels (1..32) of the background (level 0)
//     11 nnnn            a run of nnnn + 1 pixels (1..16) of the full color (level 15)
//     01 llll            one pixel of the level llll (1..14: an edge pixel)
//     10 llll mmmmmm     a run of mmmmmm + 1 pixels (1..64) of the level llll (1..14), used from 3 pixels (the large areas of
//                        the welcome picture)
// The levels are 15ths of the icon color. Longer runs are several tokens; the last byte is padded with zeros, the decoder
// stops at width x height pixels. The runs of 0 and 15 are long and the edge pixels are alone: that is what the tokens are sized for.

#include <cstdio>
#include <cstdlib>
#include <vector>
#include "icons_raw.h"

typedef std::vector<int> Pixels;

struct Icon { const char *name; const uint8_t *data; int width, height; };

static Pixels unpack(const Icon &icon) {
  Pixels p;
  for (int i = 0; i < icon.width * icon.height; i++) p.push_back((icon.data[i >> 1] >> (4 - 4 * (i & 1))) & 15);
  return p;
}

struct BitWriter {
  std::vector<uint8_t> bytes;
  int used = 0;   // bits used in the last byte
  void put(int value, int count) {   // count bits of value, most significant first
    for (int b = count - 1; b >= 0; b--) {
      if (used == 0) bytes.push_back(0);
      if ((value >> b) & 1) bytes.back() |= 0x80 >> used;
      used = (used + 1) & 7;
    }
  }
};

static std::vector<uint8_t> encode(const Pixels &p) {
  BitWriter w;
  for (size_t i = 0; i < p.size();) {
    size_t j = i;
    while (j < p.size() && p[j] == p[i]) j++;
    int left = (int)(j - i);
    const int level = p[i];
    while (left > 0) {
      if (level == 0) {
        const int n = left > 32 ? 32 : left;
        w.put(0, 2); w.put(n - 1, 5); left -= n;
      } else if (level == 15) {
        const int n = left > 16 ? 16 : left;
        w.put(3, 2); w.put(n - 1, 4); left -= n;
      } else if (left >= 3) {
        const int n = left > 64 ? 64 : left;
        w.put(2, 2); w.put(level, 4); w.put(n - 1, 6); left -= n;
      } else {
        w.put(1, 2); w.put(level, 4); left -= 1;
      }
    }
    i = j;
  }
  return w.bytes;
}

// The decoder of Display.cpp, written the same way
static Pixels decode(const std::vector<uint8_t> &bytes, int total) {
  size_t at = 0; int left = 0; uint8_t current = 0;
  auto bit = [&]() { if (!left) { current = bytes.at(at++); left = 8; } const int b = current >> 7; current <<= 1; left--; return b; };
  auto bits = [&](int n) { int v = 0; while (n--) v = (v << 1) | bit(); return v; };
  Pixels p;
  while ((int)p.size() < total) {
    const int kind = bits(2);
    int level = 0, n = 1;
    if (kind == 0) n = bits(5) + 1;
    else if (kind == 3) { level = 15; n = bits(4) + 1; }
    else if (kind == 1) level = bits(4);
    else { level = bits(4); n = bits(6) + 1; }
    while (n-- && (int)p.size() < total) p.push_back(level);
  }
  return p;
}

int main() {
  const Icon icons[] = {
    {"ICON_THERMOMETER", ICON_THERMOMETER, ICON_THERMOMETER_WIDTH, ICON_THERMOMETER_HEIGHT},
    {"ICON_DROP", ICON_DROP, ICON_DROP_WIDTH, ICON_DROP_HEIGHT},
    {"ICON_CLOCK", ICON_CLOCK, ICON_CLOCK_WIDTH, ICON_CLOCK_HEIGHT},
    {"ICON_STEAM", ICON_STEAM, ICON_STEAM_WIDTH, ICON_STEAM_HEIGHT},
    {"ICON_WELCOME", ICON_WELCOME, ICON_WELCOME_WIDTH, ICON_WELCOME_HEIGHT},
  };
  size_t rawTotal = 0, packedTotal = 0;
  printf("// Auto-generated by tools/compress_icons.cpp from tools/icons_raw.h: do not edit, run ./tools/compress_icons.sh\n"
         "// The icons as compressed 4-bit opacity masks (0 = background, 15 = full color, between = edge); the format is\n"
         "// described in tools/compress_icons.cpp and read by drawIcon() in Display.cpp.\n"
         "#pragma once\n#include <Arduino.h>\n\n");
  for (const Icon &icon : icons) {
    const Pixels source = unpack(icon);
    const std::vector<uint8_t> packed = encode(source);
    if (decode(packed, icon.width * icon.height) != source) {
      fprintf(stderr, "%s: the decoded icon differs from the source\n", icon.name);
      return 1;
    }
    const size_t raw = (source.size() + 1) / 2;
    rawTotal += raw; packedTotal += packed.size();
    printf("#define %s_WIDTH %d\n#define %s_HEIGHT %d\n", icon.name, icon.width, icon.name, icon.height);
    printf("// %zu bytes (%zu as 4-bit data)\n", packed.size(), raw);
    printf("const uint8_t %s[] PROGMEM = {", icon.name);
    for (size_t i = 0; i < packed.size(); i++) printf("%s0x%02X,", i % 12 ? " " : "\n  ", packed[i]);
    printf("\n};\n\n");
  }
  fprintf(stderr, "icons: %zu bytes as 4-bit data, %zu compressed (decoded back, identical)\n", rawTotal, packedTotal);
  return 0;
}
